import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dir=path.join(root,'data/agent-kb');
const chapters=fs.readdirSync(dir).filter(x=>x.endsWith('.md')).sort().map(file=>({
  id:file.slice(0,2), file, text:fs.readFileSync(path.join(dir,file),'utf8').replace(/^(版本|來源)：.*\n/gm,'').trim()
}));
if(chapters.length!==10) throw new Error('Expected ten knowledge chapters');
const faq=[];
for(const chapter of chapters){
  const parts=chapter.text.split('## 常見問題\n');
  if(parts[1]) for(const match of parts[1].matchAll(/### (.+)\n([^#]+)/g)) faq.push({id:chapter.id,question:match[1].trim(),answer:match[2].trim()});
}
const outputs={
 'workers/ai-proxy/src/agent-kb.generated.js':'// Generated by scripts/build-agent-kb.mjs; edit data/agent-kb/*.md.\nexport const chapters = '+JSON.stringify(chapters,null,2)+';\n',
 'assets/agent-faq.generated.js':'// Generated from the same Markdown as the worker knowledge.\nwindow.TB_AGENT_FAQ = '+JSON.stringify(faq,null,2)+';\n'
};
for(const [file,text] of Object.entries(outputs)){
 const target=path.join(root,file);
 if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==text)throw new Error(file+' is stale');}
 else fs.writeFileSync(target,text);
}
console.log('PASS knowledge build: 10 chapters, '+faq.length+' shared local FAQs');
