import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dir=path.join(root,'data/agent-kb');
const chapters=fs.readdirSync(dir).filter(x=>x.endsWith('.md')).sort().map(file=>({
  id:file.slice(0,2), file, text:fs.readFileSync(path.join(dir,file),'utf8').replace(/^(版本|來源)：.*\n/gm,'').trim()
}));
if(chapters.length!==11) throw new Error('Expected eleven knowledge chapters');
// Token budget guard (備援路徑 fallback path): base (ch01+ch10) + any optional chapter must not exceed 2850.
// 主力路徑 (MiniMax primary) 讀全本 KB，不受此限制。
const estimateTokens=text=>Math.ceil(Array.from(text).reduce((n,c)=>n+(c.codePointAt(0)>127?2:1/3),0));
const baseText=chapters.filter(c=>c.id==='01'||c.id==='10').map(c=>c.text).join('\n\n');
const BASE_TOKENS=estimateTokens(baseText);
for(const ch of chapters){
  if(ch.id==='01'||ch.id==='10') continue;
  const total=estimateTokens(baseText+'\n\n'+ch.text);
  if(total>2850) throw new Error(`Fallback budget exceeded: base(${BASE_TOKENS}) + ch${ch.id} = ${total} > 2850`);
}
const faq=[];
for(const chapter of chapters){
  const parts=chapter.text.split('## 常見問題\n');
  if(parts[1]) for(const match of parts[1].matchAll(/### (.+)\n([^#]+)/g)) faq.push({id:chapter.id,question:match[1].trim(),answer:match[2].trim()});
}
const outputs={
 'workers/ai-proxy/src/agent-kb.generated.js':'// Generated by scripts/build-agent-kb.mjs; edit data/agent-kb/*.md.\nexport const chapters = '+JSON.stringify(chapters,null,2)+';\n',
 'assets/agent-faq.generated.js':'// Generated from the same Markdown as the worker knowledge.\nwindow.TB_AGENT_FAQ = '+JSON.stringify(faq,null,2)+';\n'
};
for(const [file,text] of Object.entries(outputs)){
 const target=path.join(root,file);
 if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==text)throw new Error(file+' is stale');}
 else fs.writeFileSync(target,text);
}
// Primary path budget warning: warn if full KB exceeds 80% of KB_FULL_LIMIT (16000)
const KB_FULL_LIMIT=16000;
const KB_WARN_THRESHOLD=Math.floor(KB_FULL_LIMIT*0.8); // 12800
const fullKBTokens=estimateTokens(chapters.map(c=>c.text).join('\n\n'));
if(fullKBTokens>KB_WARN_THRESHOLD) console.warn(`⚠ WARN: 全本 KB ${fullKBTokens} token 已超過主力路徑上限的 80%（${KB_WARN_THRESHOLD}），接近退回章節選取模式`);
console.log(`PASS knowledge build: 11 chapters, ${faq.length} shared local FAQs | full KB ${fullKBTokens} tokens (limit ${KB_FULL_LIMIT}, warn at ${KB_WARN_THRESHOLD})`);
